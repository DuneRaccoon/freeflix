"""Stage 9 task 6: the SRT/VTT -> WebVTT converter.

WHAT THIS FILE CAN AND CANNOT BE EVIDENCE OF. Nothing in this repository can
execute a WebVTT parser: jsdom 25.0.1 has no ``TextTrack``, ``TextTrackCue`` or
``VTTCue``, and the backend image has no browser binary (``pyproject.toml:19``
declares playwright; ``backend/Dockerfile`` never runs ``playwright install``).
So **the property assertions below ARE the browser facts, transcribed by hand**
from the measurements in the stage 9 plan's D19. If one was transcribed wrong,
nothing in this repository will say so. That is written at the top because it
bounds every green run here: this file proves the output matches a grammar
somebody wrote down, not that a television paints a cue.

Two consequences for how it is written, both deliberate:

1. **Every expected VTT body is typed by hand and none was captured from a
   run.** ``test_release_corpus.py:35`` already records, in this repository's own
   words, that a corpus generated by the code under test "proves only that the
   parser is deterministic." A captured expectation would make every mutation
   below green by construction.
2. **"200 and the body starts with WEBVTT" is FORBIDDEN as a success criterion
   anywhere in this file**, by name, and the reason is measured: nine distinct
   malformed shapes load at ``readyState 2`` with ``load`` fired, ``error`` not
   fired and **zero cues**, and the failure is per-cue. A payload line
   containing ``-->`` even yields a cue whose text is the empty string - which
   passes a cue-count check. So every success row asserts a cue COUNT and a
   cue's TEXT, and the shared grammar check asserts that every line carrying an
   arrow is a well-formed timing line.
"""
import re

import pytest

from app.config import settings
from app.subtitles.vtt import to_webvtt


# The output grammar, transcribed from D19. Hours at least two digits, minutes
# and seconds exactly two in 0-59, the fraction exactly three, exactly one space
# each side of the arrow, and a `.` rather than SRT's comma. Anchored at both
# ends: nothing may trail the timings, which is also why the converter re-emits
# the timing line from parsed fields instead of carrying its tail across.
_TIMING_OUT = re.compile(
    r"^(?:\d{2,}:)?[0-5]\d:[0-5]\d\.\d{3} --> (?:\d{2,}:)?[0-5]\d:[0-5]\d\.\d{3}$"
)


# --------------------------------------------------------------------- fixtures
#
# PROVENANCE, stated once for the whole file: every fixture body below is
# hand-authored. There is no corpus of real sidecar files anywhere in this
# repository (``backend/tests/data/releases.tsv`` is 370 title rows of nine
# columns with no path column; ``grep -cE '\.srt|Subs/'`` over it is 0), and the
# library this box has downloaded contains zero sidecars. So these are
# assumptions about SRT in the wild, not samples of it. What they DO pin exactly
# is the converter's own output grammar, which is the thing a television reads.

# CRLF endings, numeric identifiers, an `<i>` pair, a bare `&`, a bare `<`, and
# two accented characters - the six input features of a real SRT that each have
# their own failure mode in Blink, in one 3-cue body.
SRT_THREE_CUES = (
    "1\r\n"
    "00:00:01,000 --> 00:00:02,500\r\n"
    "Café <i>fermé</i>\r\n"
    "\r\n"
    "2\r\n"
    "00:00:03,000 --> 00:00:04,000\r\n"
    "Tom & Jerry\r\n"
    "5 < 6\r\n"
    "\r\n"
    "3\r\n"
    "00:00:05,000 --> 00:00:06,000\r\n"
    "Fin\r\n"
)
SRT_THREE_CUES_VTT = (
    "WEBVTT\n"
    "\n"
    "00:00:01.000 --> 00:00:02.500\n"
    "Café <i>fermé</i>\n"
    "\n"
    "00:00:03.000 --> 00:00:04.000\n"
    "Tom &amp; Jerry\n"
    "5 &lt; 6\n"
    "\n"
    "00:00:05.000 --> 00:00:06.000\n"
    "Fin\n"
)

# A `.vtt` sidecar with SRT commas in its timings: signature-valid, and a
# measured silent zero-cue file on the television. This is the fixture that
# earns "`.vtt` is revalidated, never passed through" (D17).
VTT_WITH_COMMAS = (
    "WEBVTT\n"
    "\n"
    "1\n"
    "00:00:01,000 --> 00:00:02,000\n"
    "Hello\n"
    "\n"
    "2\n"
    "00:00:02,500 --> 00:00:03,000\n"
    "Goodbye\n"
)
VTT_WITH_COMMAS_VTT = (
    "WEBVTT\n"
    "\n"
    "00:00:01.000 --> 00:00:02.000\n"
    "Hello\n"
    "\n"
    "00:00:02.500 --> 00:00:03.000\n"
    "Goodbye\n"
)

# A `.vtt` whose seconds field is one digit - D17's own example of a
# signature-valid file that loads with zero cues.
VTT_SHORT_FIELDS = "WEBVTT\n\n00:00:1.000 --> 00:00:2.000\nShort\n"

SRT_SECONDS_CARRY = "1\n00:00:75,000 --> 00:01:20,000\nCarried\n"
SRT_MINUTES_CARRY = "1\n00:75:01,000 --> 01:16:02,000\nCarried\n"
SRT_ARROW_IN_PAYLOAD = "1\n00:00:01,000 --> 00:00:02,000\nHe said --> and left\n"
SRT_BOTH_ESCAPES = "1\n00:00:01,000 --> 00:00:02,000\n5 < 6 and <i>7</i> & 8\n"
SRT_BRACE_PREFIX = "1\n00:00:01,000 --> 00:00:02,000\n{\\an8}Top line\n"
SRT_FONT_TAG = (
    "1\n00:00:01,000 --> 00:00:02,000\n"
    '<font color="#ffffff">Spoken</font>\n'
)

# Cue 2's whole payload is a positioning override, so there is nothing left to
# show once the braces are stripped.
SRT_BRACE_ONLY_CUE = (
    "1\n00:00:01,000 --> 00:00:02,000\nKept\n"
    "\n"
    "2\n00:00:03,000 --> 00:00:04,000\n{\\an8}\n"
)

# One cue with end == start, one with end < start, one sound. Blink keeps the
# first two as invisible dead weight, so only the converter can remove them.
SRT_BAD_DURATIONS = (
    "1\n00:00:01,000 --> 00:00:01,000\nZero length\n"
    "\n"
    "2\n00:00:09,000 --> 00:00:05,000\nBackwards\n"
    "\n"
    "3\n00:00:10,000 --> 00:00:12,000\nSound\n"
)

# An ASS body, which is what arrives when a release ships `.ass` only. Its
# `H:MM:SS.cc` timestamps do not match an SRT timing regex at line start, so a
# converter that routed it through the SRT parser would answer "header-only
# success" - the exact shape a `<track>` cannot report.
ASS_BODY = (
    "[Script Info]\n"
    "ScriptType: v4.00+\n"
    "\n"
    "[V4+ Styles]\n"
    "Format: Name, Fontname, Fontsize\n"
    "Style: Default,Arial,20\n"
    "\n"
    "[Events]\n"
    "Format: Layer, Start, End, Style, Name, Text\n"
    "Dialogue: 0,0:00:01.00,0:00:03.00,Default,,Hello there\n"
)

# Just over `subtitle_max_bytes` (4 MiB), and made of cues that WOULD convert -
# so the refusal is demonstrably about the size and not about the content.
_ONE_SRT_CUE = "1\n00:00:01,000 --> 00:00:02,000\nHi\n\n"
OVERSIZE_SRT = _ONE_SRT_CUE * ((6 * 1024 * 1024) // len(_ONE_SRT_CUE) + 1)


# --------------------------------------------------- the shared grammar check

def _assert_output_grammar(result):
    """Every property of the emitted body, applied to every success fixture.

    This is the file's primary instrument and it replaces the forbidden "body
    starts with WEBVTT" check. The arrow-line count is the part that catches an
    unescaped ``-->`` in a payload: that line carries an arrow, so it joins this
    set, and it is not a well-formed timing line.
    """
    assert result.reason is None, f"unexpected refusal: {result.reason}"
    assert result.text is not None
    body = result.text

    assert result.cue_count > 0, "a zero-cue body is a refusal, never a success"
    assert "\r" not in body, "LF endings only; CR-only endings are a leniency"

    lines = body.split("\n")
    assert lines[0] == "WEBVTT", "the magic is the whole first line, exactly"
    assert lines[1] == "", "a blank line after the magic is not a leniency to lean on"

    arrow_lines = [line for line in lines if "-->" in line]
    assert len(arrow_lines) == result.cue_count, (
        "every line carrying an arrow must be one of the cue_count timing lines; "
        f"found {len(arrow_lines)} for {result.cue_count} cues: {arrow_lines}"
    )
    for line in arrow_lines:
        assert _TIMING_OUT.match(line), f"malformed timing line: {line!r}"
        assert "," not in line, f"SRT's comma survived into a timing line: {line!r}"

    assert body.endswith("\n") and not body.endswith("\n\n")


_SUCCESS_FIXTURES = [
    ("srt-three-cues", SRT_THREE_CUES, ".srt"),
    ("vtt-with-commas", VTT_WITH_COMMAS, ".vtt"),
    ("vtt-short-fields", VTT_SHORT_FIELDS, ".vtt"),
    ("srt-seconds-carry", SRT_SECONDS_CARRY, ".srt"),
    ("srt-minutes-carry", SRT_MINUTES_CARRY, ".srt"),
    ("srt-arrow-in-payload", SRT_ARROW_IN_PAYLOAD, ".srt"),
    ("srt-both-escapes", SRT_BOTH_ESCAPES, ".srt"),
    ("srt-brace-prefix", SRT_BRACE_PREFIX, ".srt"),
    ("srt-font-tag", SRT_FONT_TAG, ".srt"),
    ("srt-brace-only-cue", SRT_BRACE_ONLY_CUE, ".srt"),
    ("srt-bad-durations", SRT_BAD_DURATIONS, ".srt"),
]


@pytest.mark.parametrize(
    "text,fmt",
    [(text, fmt) for _, text, fmt in _SUCCESS_FIXTURES],
    ids=[name for name, _, _ in _SUCCESS_FIXTURES],
)
def test_every_converted_body_satisfies_the_output_grammar(text, fmt):
    _assert_output_grammar(to_webvtt(text, fmt))


def test_the_grammar_check_is_applied_to_every_success_fixture():
    """Non-vacuity, in its own row rather than trusted.

    A parametrised grammar check over an empty or shrinking list passes forever.
    """
    assert len(_SUCCESS_FIXTURES) >= 11


# ------------------------------------------------------------- byte-exact rows

def test_srt_three_cues_converts_byte_exactly():
    """One hand-typed body, one hand-typed expectation, compared whole.

    Byte-exactness is what catches spacing: two spaces around the arrow is a
    measured leniency in Chromium 155 that nobody has checked on Chromium 120,
    and no property assertion in this file looks at the single space.
    """
    result = to_webvtt(SRT_THREE_CUES, ".srt")
    assert result.text == SRT_THREE_CUES_VTT
    assert result.cue_count == 3
    assert result.reason is None


def test_vtt_with_comma_timings_is_revalidated_not_passed_through():
    """`.vtt` goes through the same decode-and-emit path, never straight out.

    A signature-valid `.vtt` carrying SRT commas loads at readyState 2 with zero
    cues and no event, so passing a `.vtt` through unchanged is indistinguishable
    from serving nothing.
    """
    result = to_webvtt(VTT_WITH_COMMAS, ".vtt")
    assert result.text == VTT_WITH_COMMAS_VTT
    assert result.cue_count == 2


def test_vtt_with_one_digit_fields_is_repaired():
    result = to_webvtt(VTT_SHORT_FIELDS, ".vtt")
    assert result.text == "WEBVTT\n\n00:00:01.000 --> 00:00:02.000\nShort\n"
    assert result.cue_count == 1


# ------------------------------------------------------------------ the carries

def test_seconds_are_carried_into_minutes():
    """``00:00:75,000`` is a measured silent zero-cue file.

    This row cannot discriminate the MINUTES carry: delete that step and this
    fixture still emits ``00:01:15.000``, because its minutes field never
    reaches 60. The next test is the other half, and one fixture cannot be both.
    """
    result = to_webvtt(SRT_SECONDS_CARRY, ".srt")
    assert result.text == "WEBVTT\n\n00:01:15.000 --> 00:01:20.000\nCarried\n"
    assert result.cue_count == 1


def test_minutes_are_carried_into_hours():
    """``00:75:01,000`` is separately measured, and separately silent.

    Delete only the seconds carry and this fixture stays green - its seconds
    field is 01. That is why the plan prescribes two mutations here and why
    these are two tests.
    """
    result = to_webvtt(SRT_MINUTES_CARRY, ".srt")
    assert result.text == "WEBVTT\n\n01:15:01.000 --> 01:16:02.000\nCarried\n"
    assert result.cue_count == 1


# ----------------------------------------------------------------- the payload

def test_an_arrow_in_a_payload_line_is_escaped():
    """A data-loss guard, not hygiene.

    Measured: a payload line containing ``-->`` yields a cue whose ``text`` is
    the empty string. The cue exists, so a cue-count check passes, and the line
    is simply gone from the picture for as long as it should have been up.
    """
    result = to_webvtt(SRT_ARROW_IN_PAYLOAD, ".srt")
    assert result.text == (
        "WEBVTT\n\n00:00:01.000 --> 00:00:02.000\nHe said --&gt; and left\n"
    )
    assert result.cue_count == 1


def test_angle_brackets_and_ampersands_are_escaped_in_opposite_directions():
    """One fixture carrying BOTH, because either alone is undiscriminating.

    A blanket ``html.escape()`` puts the literal text ``<i>`` on screen for the
    whole film; escaping nothing renders ``A &notreal; B`` as ``A ¬real; B``
    through a legacy semicolon-less entity. A fixture with only a bare ``<`` is
    green under the first mutation, and one with only a tag is green under the
    second.
    """
    result = to_webvtt(SRT_BOTH_ESCAPES, ".srt")
    assert result.text == (
        "WEBVTT\n\n00:00:01.000 --> 00:00:02.000\n"
        "5 &lt; 6 and <i>7</i> &amp; 8\n"
    )
    assert result.cue_count == 1


def test_brace_runs_are_stripped_before_escaping():
    """``{\\an8}Top line`` renders the braces literally in Blink."""
    result = to_webvtt(SRT_BRACE_PREFIX, ".srt")
    assert result.text == "WEBVTT\n\n00:00:01.000 --> 00:00:02.000\nTop line\n"
    assert result.cue_count == 1


def test_a_font_tag_survives_verbatim():
    """The ``Does not strip <font ...>`` rule, pinned behaviourally.

    Blink drops the tag and keeps the text, which it can only do if the tag
    arrives AS a tag. Escaping it is not "stripping" it and so satisfies the
    letter of D19's allow-list sentence, while putting
    ``<font color="#ffffff">`` on screen - strictly worse than either
    alternative. See the module docstring of ``app/subtitles/vtt.py``.
    """
    result = to_webvtt(SRT_FONT_TAG, ".srt")
    assert result.text == (
        "WEBVTT\n\n00:00:01.000 --> 00:00:02.000\n"
        '<font color="#ffffff">Spoken</font>\n'
    )
    assert result.cue_count == 1


def test_a_cue_whose_whole_payload_is_a_brace_run_is_dropped():
    result = to_webvtt(SRT_BRACE_ONLY_CUE, ".srt")
    assert result.cue_count == 1, "the positioning-only cue must not be emitted"
    assert result.text == "WEBVTT\n\n00:00:01.000 --> 00:00:02.000\nKept\n"


def test_cues_whose_end_is_not_after_their_start_are_dropped():
    """Exact count, because Blink keeps these as invisible dead weight."""
    result = to_webvtt(SRT_BAD_DURATIONS, ".srt")
    assert result.cue_count == 1
    assert result.text == "WEBVTT\n\n00:00:10.000 --> 00:00:12.000\nSound\n"


# ---------------------------------------------------------------- the refusals

_REFUSALS = [
    ("empty", "", ".srt", "empty"),
    ("whitespace-only", "   \n\t\n  \n", ".srt", "blank"),
    ("ass-body-as-srt", ASS_BODY, ".srt", "no-cues"),
    ("oversize", OVERSIZE_SRT, ".srt", "too-large"),
]


@pytest.mark.parametrize(
    "text,fmt,reason",
    [(text, fmt, reason) for _, text, fmt, reason in _REFUSALS],
    ids=[name for name, _, _, _ in _REFUSALS],
)
def test_a_body_with_no_usable_cues_is_refused_with_a_reason(text, fmt, reason):
    """The most important assertion in the stage, and here is why.

    Measured: a raw empty body and a header-less body each fire a real ``error``
    event on the media element. Wrap either in ``WEBVTT\\n\\n`` and it becomes a
    load at ``readyState 2`` with zero cues and **no event at all** - a loud
    failure converted into an unobservable one, with the television showing a
    blank picture and no way to say why.

    So: no body, a reason, and ``cue_count`` 0. Four reasons for four fixtures,
    because "something was wrong with the file" is not a sentence a viewer can
    act on, and the route turns each of these into a distinct 415.
    """
    result = to_webvtt(text, fmt)
    assert result.reason == reason
    assert result.text is None
    assert result.cue_count == 0


def test_the_four_refusal_reasons_are_pairwise_distinct():
    """Otherwise the route's 415 body is the same sentence four times over."""
    reasons = [reason for _, _, _, reason in _REFUSALS]
    assert len(set(reasons)) == len(reasons) == 4


def test_the_oversize_fixture_is_actually_over_the_cap():
    """Non-vacuity for the ``too-large`` row.

    Its body is made of cues that WOULD convert, so a green row above means the
    size gate fired and not the parser. If the cap were ever raised past 6 MiB
    this assertion is the one that says so, rather than the refusal row quietly
    becoming a test of nothing.
    """
    assert len(OVERSIZE_SRT.encode("utf-8")) > settings.subtitle_max_bytes
    assert to_webvtt(_ONE_SRT_CUE, ".srt").cue_count == 1


# ----------------------------------------------------------- format refusal

@pytest.mark.parametrize("fmt", [".ass", ".ssa", "ass", ".ASS"])
def test_ass_and_ssa_are_refused_by_format_and_never_parsed(fmt):
    """Declining a spec commitment, with grounds (plan D17).

    The refusal reads off ``settings.subtitle_convertible_extensions``, not a
    literal set here, which is what makes ``test_subtitle_config.py``'s
    "convertible is a subset of listed" assertion mean something: move ``.ass``
    into the convertible set and this row is the one that reddens.

    A converter that routed this body through the SRT parser would answer with
    no reason at all (or ``no-cues``), i.e. a header-only "success" - and a
    header-only body is exactly the shape a ``<track>`` reports as a clean load.
    """
    result = to_webvtt(ASS_BODY, fmt)
    assert result.reason == "unsupported-format"
    assert result.text is None
    assert result.cue_count == 0


@pytest.mark.parametrize("fmt", ["srt", ".SRT", ".srt", "vtt"])
def test_the_format_argument_is_accepted_with_or_without_its_dot(fmt):
    """The lister reports ``"srt"``; the plan's own examples pass ``".srt"``.

    Both spellings reaching the same answer is cheaper than a trap for whichever
    caller guesses wrong.
    """
    body = VTT_WITH_COMMAS if fmt.lower().lstrip(".") == "vtt" else SRT_THREE_CUES
    assert to_webvtt(body, fmt).reason is None


def test_an_unknown_extension_is_refused_rather_than_guessed():
    for fmt in (".txt", ".sub", ".idx", ".sup", "", "."):
        result = to_webvtt(SRT_THREE_CUES, fmt)
        assert result.reason == "unsupported-format", fmt
        assert result.text is None
