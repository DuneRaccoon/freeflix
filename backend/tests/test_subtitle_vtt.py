# ---------------------------------------------------------------- the refusals

_REFUSALS = [
    ("empty", "", ".srt", "empty"),
    ("whitespace-only", "   \n\t\n  \n", ".srt", "blank"),
    ("ass-body-as-srt", ASS_BODY, ".srt", "no-cues"),
    ("oversize", OVERSIZE_SRT, ".srt", "too-large"),
]


@pytest.mark.parametrize(
    "text,fmt,reason",
    [(text, fmt, reason) for _, text, fmt, reason in _REFUSALS],
    ids=[name for name, _, _, _ in _REFUSALS],
)
def test_a_body_with_no_usable_cues_is_refused_with_a_reason(text, fmt, reason):
    """The most important assertion in the stage, and here is why.

    Measured: a raw empty body and a header-less body each fire a real ``error``
    event on the media element. Wrap either in ``WEBVTT\\n\\n`` and it becomes a
    load at ``readyState 2`` with zero cues and **no event at all** - a loud
    failure converted into an unobservable one, with the television showing a
    blank picture and no way to say why.

    So: no body, a reason, and ``cue_count`` 0. Four reasons for four fixtures,
    because "something was wrong with the file" is not a sentence a viewer can
    act on, and the route turns each of these into a distinct 415.
    """
    result = to_webvtt(text, fmt)
    assert result.reason == reason
    assert result.text is None
    assert result.cue_count == 0


def test_the_four_refusal_reasons_are_pairwise_distinct():
    """Otherwise the route's 415 body is the same sentence four times over."""
    reasons = [reason for _, _, _, reason in _REFUSALS]
    assert len(set(reasons)) == len(reasons) == 4


def test_the_oversize_fixture_is_actually_over_the_cap():
    """Non-vacuity for the ``too-large`` row.

    Its body is made of cues that WOULD convert, so a green row above means the
    size gate fired and not the parser. If the cap were ever raised past 6 MiB
    this assertion is the one that says so, rather than the refusal row quietly
    becoming a test of nothing.
    """
    assert len(OVERSIZE_SRT.encode("utf-8")) > settings.subtitle_max_bytes
    assert to_webvtt(_ONE_SRT_CUE, ".srt").cue_count == 1


