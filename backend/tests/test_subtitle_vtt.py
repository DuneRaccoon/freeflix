# The output grammar, transcribed from D19. Hours at least two digits, minutes
# and seconds exactly two in 0-59, the fraction exactly three, exactly one space
# each side of the arrow, and a `.` rather than SRT's comma. Anchored at both
# ends: nothing may trail the timings, which is also why the converter re-emits
# the timing line from parsed fields instead of carrying its tail across.
_TIMING_OUT = re.compile(
    r"^(?:\d{2,}:)?[0-5]\d:[0-5]\d\.\d{3} --> (?:\d{2,}:)?[0-5]\d:[0-5]\d\.\d{3}$"
)


