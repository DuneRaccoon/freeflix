# --------------------------------------------------- the shared grammar check

def _assert_output_grammar(result):
    """Every property of the emitted body, applied to every success fixture.

    This is the file's primary instrument and it replaces the forbidden "body
    starts with WEBVTT" check. The arrow-line count is the part that catches an
    unescaped ``-->`` in a payload: that line carries an arrow, so it joins this
    set, and it is not a well-formed timing line.
    """
    assert result.reason is None, f"unexpected refusal: {result.reason}"
    assert result.text is not None
    body = result.text

    assert result.cue_count > 0, "a zero-cue body is a refusal, never a success"
    assert "\r" not in body, "LF endings only; CR-only endings are a leniency"

    lines = body.split("\n")
    assert lines[0] == "WEBVTT", "the magic is the whole first line, exactly"
    assert lines[1] == "", "a blank line after the magic is not a leniency to lean on"

    arrow_lines = [line for line in lines if "-->" in line]
    assert len(arrow_lines) == result.cue_count, (
        "every line carrying an arrow must be one of the cue_count timing lines; "
        f"found {len(arrow_lines)} for {result.cue_count} cues: {arrow_lines}"
    )
    for line in arrow_lines:
        assert _TIMING_OUT.match(line), f"malformed timing line: {line!r}"
        assert "," not in line, f"SRT's comma survived into a timing line: {line!r}"

    assert body.endswith("\n") and not body.endswith("\n\n")


