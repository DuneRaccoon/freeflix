"""Stage 9 task 6: the SRT/VTT -> WebVTT converter.

WHAT THIS FILE CAN AND CANNOT BE EVIDENCE OF. Nothing in this repository can
execute a WebVTT parser: jsdom 25.0.1 has no ``TextTrack``, ``TextTrackCue`` or
``VTTCue``, and the backend image has no browser binary (``pyproject.toml:19``
declares playwright; ``backend/Dockerfile`` never runs ``playwright install``).
So **the property assertions below ARE the browser facts, transcribed by hand**
from the measurements in the stage 9 plan's D19. If one was transcribed wrong,
nothing in this repository will say so. That is written at the top because it
bounds every green run here: this file proves the output matches a grammar
somebody wrote down, not that a television paints a cue.

Two consequences for how it is written, both deliberate:

1. **Every expected VTT body is typed by hand and none was captured from a
   run.** ``test_release_corpus.py:35`` already records, in this repository's own
   words, that a corpus generated by the code under test "proves only that the
   parser is deterministic." A captured expectation would make every mutation
   below green by construction.
2. **"200 and the body starts with WEBVTT" is FORBIDDEN as a success criterion
   anywhere in this file**, by name, and the reason is measured: nine distinct
   malformed shapes load at ``readyState 2`` with ``load`` fired, ``error`` not
   fired and **zero cues**, and the failure is per-cue. A payload line
   containing ``-->`` even yields a cue whose text is the empty string - which
   passes a cue-count check. So every success row asserts a cue COUNT and a
   cue's TEXT, and the shared grammar check asserts that every line carrying an
   arrow is a well-formed timing line.
"""
